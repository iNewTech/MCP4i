-- One-time setup, run with SQL naming after creating library MCPLIB.
-- Rebuilds must not rerun this file: existing catalog and registry rows survive.
-- MCPCFGTMPL/MCPTOOLTPL remain empty templates. Create each server's Snnnnnnn /
-- Tnnnnnnn tables LIKE these templates INCLUDING COLUMN DEFAULTS; reproduce
-- the keys and CHECK constraints on generated tables as part of creation.
-- All object, column, and constraint names fit IBM i's ten-character names.
CREATE TABLE MCPLIB.MCPSERVERS (
    SRVID CHAR(10) NOT NULL PRIMARY KEY,
    DISPNAME VARCHAR(64) NOT NULL,
    PORT INTEGER NOT NULL UNIQUE CHECK (PORT BETWEEN 1024 AND 65535),
    CFGFILE CHAR(10) NOT NULL UNIQUE,
    TOOLFILE CHAR(10) NOT NULL UNIQUE,
    MAXLVL CHAR(1) NOT NULL DEFAULT 'R' CHECK (MAXLVL IN ('R', 'W', 'D')),
    STATE CHAR(1) NOT NULL DEFAULT 'D' CHECK (STATE IN ('D', 'A', 'X')),
    CRTBY VARCHAR(10) NOT NULL DEFAULT '',
    CHGBY VARCHAR(10) NOT NULL DEFAULT '',
    CRTTS TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHGTS TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE MCPLIB.MCPCFGTMPL (
    CFGID INTEGER NOT NULL PRIMARY KEY CHECK (CFGID = 1),
    LIBLIST VARCHAR(2750) NOT NULL DEFAULT '',
    TIMEOUT INTEGER NOT NULL DEFAULT 30 CHECK (TIMEOUT BETWEEN 1 AND 3600)
);

CREATE TABLE MCPLIB.MCPTOOLTPL (
    TOOLNAME VARCHAR(64) NOT NULL PRIMARY KEY,
    DESCR VARCHAR(256) NOT NULL,
    HDLLIB CHAR(10) NOT NULL,
    HDLPGM CHAR(10) NOT NULL,
    -- HDLLIB/HDLPGM is always the MCP four-parameter wrapper. A generated
    -- wrapper calls the separate native target identified below.
    GENMODE CHAR(1) NOT NULL DEFAULT 'M' CHECK (GENMODE IN ('M', 'G', 'T')),
    TGTLIB CHAR(10) NOT NULL DEFAULT '',
    TGTPGM CHAR(10) NOT NULL DEFAULT '',
    TOOL_LVL CHAR(1) NOT NULL DEFAULT 'R' CHECK (TOOL_LVL IN ('R', 'W', 'D')),
    STATE CHAR(1) NOT NULL DEFAULT 'D' CHECK (STATE IN ('D', 'A', 'X')),
    SCHEMAJSON VARCHAR(2048) NOT NULL DEFAULT '{"type":"object","properties":{}}',
    ARG1NAME VARCHAR(128) NOT NULL DEFAULT '',
    ARG1TYPE VARCHAR(7) NOT NULL DEFAULT 'string'
        CHECK (ARG1TYPE IN ('string', 'integer', 'number', 'boolean')),
    ARG1REQ CHAR(1) NOT NULL DEFAULT 'N' CHECK (ARG1REQ IN ('Y', 'N')),
    ARG2NAME VARCHAR(128) NOT NULL DEFAULT '',
    ARG2TYPE VARCHAR(7) NOT NULL DEFAULT 'string'
        CHECK (ARG2TYPE IN ('string', 'integer', 'number', 'boolean')),
    ARG2REQ CHAR(1) NOT NULL DEFAULT 'N' CHECK (ARG2REQ IN ('Y', 'N')),
    ARG3NAME VARCHAR(128) NOT NULL DEFAULT '',
    ARG3TYPE VARCHAR(7) NOT NULL DEFAULT 'string'
        CHECK (ARG3TYPE IN ('string', 'integer', 'number', 'boolean')),
    ARG3REQ CHAR(1) NOT NULL DEFAULT 'N' CHECK (ARG3REQ IN ('Y', 'N')),
    CRTBY VARCHAR(10) NOT NULL DEFAULT '',
    CHGBY VARCHAR(10) NOT NULL DEFAULT '',
    CRTTS TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHGTS TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT READACTIVE CHECK (STATE <> 'A' OR TOOL_LVL = 'R'),
    CONSTRAINT GENTARGET CHECK (GENMODE = 'M' OR
        (TGTLIB <> '' AND TGTPGM <> ''))
);
